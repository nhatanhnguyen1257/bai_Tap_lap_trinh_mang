    @Override
    public <T> void loading(T input) {
        WorkerService worker = new WorkerService();
        response = worker.detail((Long) input);
        
        jTextFullName.setText(response.getFullName());
        jTextSalary.setText(String.valueOf(response.getSalary()));
        jTextBirthDay.setText(response.getBirthday());
        
        CommomService commomService = new CommomService();
        commomService.setViewProvince(combox_provider);
        
        ProvinceEntity province = new ProvinceEntity();
        province.setCode(response.getProvinceCode());
        commomService.setViewDistrict(combox_districts, province);
        
        DistrictEntity district = new DistrictEntity();
        district.setCode(response.getDistrictCode());
        commomService.setViewWard(combox_ward, province, district);
        setItem(combox_provider, response.getProvinceCode());
        setItem(combox_districts, response.getDistrictCode());
        setItem(combox_ward, response.getWardCode());
    }
    
    private <T> List<T> getAllItems(JComboBox<T> cb) {
        List<T> list = new ArrayList<>();
        for (int i = 0; i < cb.getItemCount(); i++){
            list.add((T) cb.getItemAt(i));
        }
        return list;
    }
    
    
    private <T> void setItem(JComboBox<T> comboBox, String code) {
        List<T> data = getAllItems(comboBox);
        for (int i = 0; i < data.size(); i++) {
           if (data.get(i) instanceof ProvinceEntity) {
                if (((ProvinceEntity)data.get(i)).getCode().equals(code)) {
                    comboBox.setSelectedIndex(i);
                    provinceSelect = ((ProvinceEntity)data.get(i));
                    return;
                }
            } else if (data.get(i) instanceof DistrictEntity){
                if (((DistrictEntity)data.get(i)).getCode().equals(code)) {
                    comboBox.setSelectedIndex(i);
                    districtSelect = ((DistrictEntity)data.get(i));
                    return;
                }
            } else if (data.get(i) instanceof WardEntity){
                if (((WardEntity)data.get(i)).getCode().equals(code)) {
                    comboBox.setSelectedIndex(i);
                    wardSelect = ((WardEntity)data.get(i));
                    return;
                }
            } 
        }
    }
    
