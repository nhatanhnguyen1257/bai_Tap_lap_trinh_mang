    private void jButtonUpdateMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButtonUpdateMouseClicked
        String txt = CommomService.checkDate(jTextBirthDay.getText());
        if (txt == null) {
            WorkerService worker = new WorkerService();
            response.setProvinceCode(provinceSelect.getCode());
            response.setDistrictCode(districtSelect.getCode());
            response.setWardCode(wardSelect.getCode());
            response.setFullName(jTextFullName.getText());
            response.setSalary(jTextSalary.getText().isEmpty() ? 0L : Long.valueOf(jTextSalary.getText()));
            response.setBirthday(jTextBirthDay.getText());
        if ( worker.update(response)) {
            JOptionPane.showMessageDialog( SwingUtilities.getWindowAncestor(this), "Cap nhat thanh cong");
            App app = (App) SwingUtilities.getWindowAncestor(this);
            app.back(null);
        } else {
            JOptionPane.showMessageDialog( SwingUtilities.getWindowAncestor(this), "Cap nhat that bai");
        }
        } else {
            JOptionPane.showMessageDialog( SwingUtilities.getWindowAncestor(this), txt);
        }
        
    }//GEN-LAST:event_jButtonUpdateMouseClicked

